const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {EarthEvents,defenseBonus,SHAPES}=
  require("../app/src/main/assets/earth-events.js");
const {Game}=require("../app/src/main/assets/engine.js");
const geometry={W:390,earth:{x:195,y:1240,r:184}};
test("PT039: Earth events start after a delay and all seven shapes are reachable",()=>{
 const e=new EarthEvents(()=>0);
 assert.equal(e.tick(8,geometry).length,0);
 assert.equal(e.tick(9,geometry)[0].type,"earth-spawn");
 assert.equal(e.active.type,0);
 const types=new Set([e.active.type]);
 // Repeated zero RNG must not select consecutive equal forms.
 for(let k=0;k<14;k++){
   e.resolve(e.active.start+1,"satellite");
   e.spawn(30+k*20,geometry);
   assert.notEqual(e.active.type,e.lastBefore);
   types.add(e.active.type);
   e.lastBefore=e.active.type;
 }
 assert.ok(types.size>=2);
 assert.equal(SHAPES.length,7);
});
test("PT039: the seven varieties can be generated by distinct random inputs",()=>{
 const seen=new Set();
 for(let k=0;k<7;k++){
   const e=new EarthEvents(()=>k/7);
   e.spawn(10,geometry);seen.add(e.active.type);
 }
 assert.equal(seen.size,7);
});
test("PT039: moving objects approach Earth's visible surface",()=>{
 const e=new EarthEvents(()=>0.25);e.spawn(10,geometry);
 const first=e.position(e.active,10),middle=e.position(e.active,12.5);
 const last=e.position(e.active,10+e.active.duration);
 assert.ok(first.y<middle.y&&middle.y<last.y);
 assert.ok(Math.abs(last.y-(geometry.earth.y-geometry.earth.r))<12);
 assert.ok(first.x!==last.x);
});
test("PT039: satellite interception and spontaneous explosion do not award points",()=>{
 for(const [rng,reason] of [[()=>0,"satellite"],[()=>0.99,"spontaneous"]]){
   const e=new EarthEvents(rng),g=new Game(()=>0);
   e.spawn(10,geometry);
   const event=e.tick(10+e.active.duration+0.01,geometry)[0];
   assert.equal(event.reason,reason);
   assert.equal(g.score,0);
   assert.equal(e.active,null);
   assert.equal(e.effects.length,1);
 }
});
test("PT039: manual aim must hit visible object and can reward exactly once",()=>{
 const e=new EarthEvents(()=>0);e.spawn(10,geometry);
 const center=e.position(e.active,12);
 assert.equal(e.hit(center.x+80,center.y,12,8),null);
 const shot=e.hit(center.x,center.y,12,8);
 assert.equal(shot.reason,"player");
 assert.equal(shot.bonus,120);
 assert.equal(e.hit(center.x,center.y,12,8),null);
});
test("PT039: manual bonus is the square of permanent gravity speed with cap",()=>{
 assert.equal(defenseBonus(8),120);
 assert.equal(defenseBonus(4),480);
 assert.equal(defenseBonus(2),1920);
 assert.equal(defenseBonus(.8),3000); // cap x25 prevents score explosion
 assert.equal(defenseBonus(NaN),120);
 const g=new Game(()=>0);
 assert.equal(g.award(defenseBonus(g.fallInterval()),"earth-defense"),120);
});
test("PT039: arbitrary render remains fully independent of game collision",()=>{
 const e=new EarthEvents(()=>0);e.spawn(10,geometry);
 const calls=[];
 const ctx=new Proxy({},{
   get(_t,k){
     if(k==="save"||k==="restore"||k==="beginPath"||k==="moveTo"||
        k==="lineTo"||k==="arc"||k==="stroke"||k==="fill"||k==="fillRect"||
        k==="strokeRect"||k==="translate"||k==="rotate")
       return (...v)=>calls.push([k,...v]);
     return undefined;
   },set(){return true}
 });
 assert.doesNotThrow(()=>e.draw(ctx,{now:10.4}));
 assert.ok(calls.some(v=>v[0]==="fillRect"));
 const g=new Game(()=>0);
 assert.equal(g.score,0);assert.equal(g.board[0][0],-1);
});
